import { Injectable } from '@nestjs/common'
import PDFDocument from 'pdfkit'

const PAGE_MARGIN = 56

export interface SignalReportLinkedCase {
  referenceNumber: string
  status: string
}

export interface SignalReportData {
  title: string
  description: string
  detectionMethod: string
  productIdentifier: string
  batchNumber: string | null
  status: string
  previousAwareness: boolean | null
  previousAwarenessNote: string | null
  strengthOfEvidenceCaseCount: number | null
  clinicalRelevanceNote: string | null
  severityNote: string | null
  patientExposureNote: string | null
  expectedRegulatoryResponseNote: string | null
  assessmentNote: string | null
  recommendationAction: string | null
  recommendationNote: string | null
  linkedCases: SignalReportLinkedCase[]
  companyName: string
  generatedByUserFullName: string
  generatedAt: Date
  createdAt: Date
}

function formatDate(value: Date): string {
  return value.toISOString().slice(0, 10)
}

/** Every `.text()` call here is ambient (no explicit x/y, no tables) — the pdfkit cursor-leak bug class this codebase has hit three times only bites when an earlier call pins an explicit x/y a later ambient call then inherits; a purely sequential document like this one never does. */
@Injectable()
export class SignalReportPdfService {
  async render(data: SignalReportData): Promise<Buffer> {
    const doc = new PDFDocument({ size: 'A4', margin: PAGE_MARGIN })
    const chunks: Buffer[] = []

    const result = new Promise<Buffer>((resolve, reject) => {
      doc.on('data', (chunk: Buffer) => chunks.push(chunk))
      doc.on('end', () => resolve(Buffer.concat(chunks)))
      doc.on('error', reject)
    })

    const section = (heading: string) => {
      doc.moveDown(0.8)
      doc.font('Helvetica-Bold').fontSize(11).fillColor('#000000').text(heading)
      doc.font('Helvetica').fontSize(10)
      doc.moveDown(0.3)
    }
    const field = (label: string, value: string | null | undefined) => {
      doc.font('Helvetica-Bold').text(`${label}: `, { continued: true })
      doc.font('Helvetica').text(value && value.trim().length > 0 ? value : 'Not recorded')
    }

    doc.font('Helvetica-Bold').fontSize(14).text('SIGNAL MANAGEMENT REPORT')
    doc.font('Helvetica').fontSize(9).fillColor('#6B7280')
    doc.text(`${data.companyName} — Pharmacovigilance`)
    doc.text(`Generated ${formatDate(data.generatedAt)} by ${data.generatedByUserFullName}`)
    doc.fillColor('#000000').fontSize(10)

    section('1. Signal Identification')
    field('Title', data.title)
    field('Description', data.description)
    field('Detection Method', data.detectionMethod === 'pattern_flag' ? 'Automated pattern-flag detection' : 'Manually raised')
    field('Product', data.productIdentifier)
    field('Batch Number', data.batchNumber)
    field('Date Raised', formatDate(data.createdAt))
    field('Current Status', data.status.replace(/_/g, ' '))

    section('2. Validation (GVP Module IX §IX.B.3)')
    field('Previously Known?', data.previousAwareness === null ? null : data.previousAwareness ? 'Yes' : 'No')
    field('Previous Awareness Note', data.previousAwarenessNote)
    field('Strength of Evidence (de-duplicated case count)', data.strengthOfEvidenceCaseCount?.toString() ?? null)
    field('Clinical Relevance', data.clinicalRelevanceNote)

    section('3. Analysis & Prioritisation (GVP Module IX §IX.B.4)')
    field('Severity', data.severityNote)
    field('Patient Exposure', data.patientExposureNote)
    field('Expected Regulatory Response', data.expectedRegulatoryResponseNote)

    section('4. Assessment')
    field('Assessment', data.assessmentNote)

    section('5. Recommendation for Action (GVP Module IX §IX.C.7)')
    field('Recommended Action', data.recommendationAction ? data.recommendationAction.replace(/_/g, ' ') : null)
    field('Recommendation Note', data.recommendationNote)

    section(`6. Evidence Cases (${data.linkedCases.length})`)
    if (data.linkedCases.length === 0) {
      doc.text('No cases linked.')
    } else {
      for (const c of data.linkedCases) {
        doc.text(`•  ${c.referenceNumber} — ${c.status.replace(/_/g, ' ')}`, { indent: 12 })
      }
    }

    doc.moveDown(1.5)
    doc.fontSize(8.5).fillColor('#6B7280').text(
      'This report is generated by SafeMeds from the signal record as it stood at generation time. It does not itself constitute submission to any regulatory authority — attach proof of submission separately once dispatched.',
      { align: 'justify' },
    )

    doc.end()
    return result
  }
}
