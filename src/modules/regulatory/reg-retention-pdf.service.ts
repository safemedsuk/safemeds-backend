import { Injectable } from '@nestjs/common'
import PDFDocument from 'pdfkit'

const PAGE_MARGIN = 40
const CONTENT_WIDTH = 595.28 - PAGE_MARGIN * 2 // A4 width in points, minus margins

const COLOR_BAR = '#0F6B66'
const COLOR_BAR_TEXT = '#FFFFFF'
const COLOR_TEXT = '#1F2937'
const COLOR_MUTED = '#6B7280'
const COLOR_BORDER = '#D1D5DB'

export interface RegRetentionCertificateData {
  companyName: string
  productBrandName: string
  registrationNumber: string
  authorityName: string
  year: number
  displayCode: string
  paidAt: Date
  createdByName: string
}

function formatDate(value: Date): string {
  return value.toISOString().slice(0, 10)
}

/**
 * testing-correction-explanation.md §3.3 — a real, honest **internal**
 * certificate that a registration's annual retention was paid and logged
 * — never a fabricated regulatory document, mirroring
 * `RegPostMarketObligationPdfService`'s exact shape and the same
 * deliberate no-letterhead choice (this isn't a document *to* the
 * regulator, it's the company's own kept-for-their-records proof).
 */
@Injectable()
export class RegRetentionPdfService {
  async render(data: RegRetentionCertificateData): Promise<Buffer> {
    const doc = new PDFDocument({ size: 'A4', margin: PAGE_MARGIN, bufferPages: true })
    const chunks: Buffer[] = []

    const result = new Promise<Buffer>((resolve, reject) => {
      doc.on('data', (chunk: Buffer) => chunks.push(chunk))
      doc.on('end', () => resolve(Buffer.concat(chunks)))
      doc.on('error', reject)
    })

    doc
      .font('Helvetica-Bold')
      .fontSize(14)
      .fillColor(COLOR_BAR)
      .text('Registration Retention — Certificate', { align: 'center' })
    doc
      .font('Helvetica')
      .fontSize(8)
      .fillColor(COLOR_MUTED)
      .text(
        'An internal record confirming this registration’s annual retention has been paid and logged — not itself a regulatory submission.',
        { align: 'center' },
      )
    doc.moveDown(1)
    doc
      .moveTo(PAGE_MARGIN, doc.y)
      .lineTo(PAGE_MARGIN + CONTENT_WIDTH, doc.y)
      .strokeColor(COLOR_BORDER)
      .lineWidth(1)
      .stroke()
    doc.moveDown(1)

    const field = (label: string, value: string) => {
      doc.font('Helvetica').fontSize(8).fillColor(COLOR_MUTED).text(label.toUpperCase())
      doc.font('Helvetica').fontSize(10).fillColor(COLOR_TEXT).text(value)
      doc.moveDown(0.5)
    }

    field('Reference', data.displayCode)
    field('Company', data.companyName)
    field('Product', data.productBrandName)
    field('Registration Number', data.registrationNumber)
    field('Authority', data.authorityName)
    field('Retention Year', String(data.year))
    field('Paid', `${formatDate(data.paidAt)}, logged by ${data.createdByName}`)

    doc.moveDown(1.5)
    doc.font('Helvetica-Bold').fontSize(9).fillColor(COLOR_BAR_TEXT)
    doc.rect(PAGE_MARGIN, doc.y, CONTENT_WIDTH, 20).fill(COLOR_BAR)
    doc
      .fillColor(COLOR_BAR_TEXT)
      .text(
        'This certificate is generated by SafeMeds for internal compliance tracking only.',
        PAGE_MARGIN + 8,
        doc.y - 15,
      )

    doc.end()
    return result
  }
}
