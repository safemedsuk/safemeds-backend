import { Injectable } from '@nestjs/common'
import PDFDocument from 'pdfkit'

const PAGE_MARGIN = 40
const CONTENT_WIDTH = 595.28 - PAGE_MARGIN * 2 // A4 width in points, minus margins

const COLOR_BAR = '#0F6B66'
const COLOR_BAR_TEXT = '#FFFFFF'
const COLOR_TEXT = '#1F2937'
const COLOR_MUTED = '#6B7280'
const COLOR_BORDER = '#D1D5DB'

export interface RegPostMarketObligationFilingRecordData {
  companyName: string
  productBrandName: string
  registrationNumber: string
  authorityName: string
  obligationType: string
  periodStart: Date | null
  periodEnd: Date
  fulfilledAt: Date
  fulfilledByName: string
  note: string | null
}

function formatDate(value: Date): string {
  return value.toISOString().slice(0, 10)
}

/**
 * RegCloud (Phase 12) Stage 8 — a real, honest **internal** record that a
 * post-market obligation was filed — never a fabricated regulatory
 * submission. Deliberately not a full "portfolio status report" style
 * document (that's Stage 17's own future dashboard-level output, per
 * `todo-regcloud.md`) and deliberately carries no letterhead — this isn't
 * a document *to* the regulator, it's the tenant's own kept-for-their-
 * records proof of what they filed and when, satisfying the same
 * "reuse `GeneratedReport` for the actual generated obligation-report
 * artifacts" instruction the build spec calls for, without inventing any
 * regulatory content this codebase has no sourced basis for.
 */
@Injectable()
export class RegPostMarketObligationPdfService {
  async render(data: RegPostMarketObligationFilingRecordData): Promise<Buffer> {
    const doc = new PDFDocument({ size: 'A4', margin: PAGE_MARGIN, bufferPages: true })
    const chunks: Buffer[] = []

    const result = new Promise<Buffer>((resolve, reject) => {
      doc.on('data', (chunk: Buffer) => chunks.push(chunk))
      doc.on('end', () => resolve(Buffer.concat(chunks)))
      doc.on('error', reject)
    })

    doc
      .font('Helvetica-Bold')
      .fontSize(14)
      .fillColor(COLOR_BAR)
      .text('Post-Market Obligation — Filing Record', { align: 'center' })
    doc
      .font('Helvetica')
      .fontSize(8)
      .fillColor(COLOR_MUTED)
      .text(
        'An internal record of a filing, kept for the company’s own compliance history — not itself a regulatory submission.',
        { align: 'center' },
      )
    doc.moveDown(1)
    doc
      .moveTo(PAGE_MARGIN, doc.y)
      .lineTo(PAGE_MARGIN + CONTENT_WIDTH, doc.y)
      .strokeColor(COLOR_BORDER)
      .lineWidth(1)
      .stroke()
    doc.moveDown(1)

    const field = (label: string, value: string) => {
      doc.font('Helvetica').fontSize(8).fillColor(COLOR_MUTED).text(label.toUpperCase())
      doc.font('Helvetica').fontSize(10).fillColor(COLOR_TEXT).text(value)
      doc.moveDown(0.5)
    }

    field('Company', data.companyName)
    field('Product', data.productBrandName)
    field('Registration Number', data.registrationNumber)
    field('Authority', data.authorityName)
    field('Obligation Type', data.obligationType.replace(/_/g, ' '))
    field(
      'Period Covered',
      data.periodStart
        ? `${formatDate(data.periodStart)} to ${formatDate(data.periodEnd)}`
        : `Up to ${formatDate(data.periodEnd)}`,
    )
    field('Filed', `${formatDate(data.fulfilledAt)} by ${data.fulfilledByName}`)
    if (data.note) field('Note', data.note)

    doc.moveDown(1.5)
    doc.font('Helvetica-Bold').fontSize(9).fillColor(COLOR_BAR_TEXT)
    doc.rect(PAGE_MARGIN, doc.y, CONTENT_WIDTH, 20).fill(COLOR_BAR)
    doc
      .fillColor(COLOR_BAR_TEXT)
      .text(
        'This record is generated by SafeMeds for internal compliance tracking only.',
        PAGE_MARGIN + 8,
        doc.y - 15,
      )

    doc.end()
    return result
  }
}
