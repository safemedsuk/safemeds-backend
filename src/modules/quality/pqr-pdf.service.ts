import { Injectable } from '@nestjs/common'
import PDFDocument from 'pdfkit'

const PAGE_MARGIN = 56

export interface PqrData {
  companyName: string
  productName: string
  periodStart: Date
  periodEnd: Date
  batchCount: number
  deviationCount: number
  capaCount: number
  oosCount: number
  complaintCount: number
  changeControlCount: number
  regSubmissionCount: number
  regVariationCount: number
  openQualityTrendFlags: string[]
  stabilityNote: string
  conclusionsNarrative: string | null
  trendsNarrative: string | null
  recommendedActions: { description: string; capaOpened: boolean }[]
  reviewedByFullName: string | null
  reviewedAt: Date | null
  generatedAt: Date
}

function formatDate(value: Date): string {
  return value.toISOString().slice(0, 10)
}

/**
 * QualCloud (Phase 13) Stage 13 — Product Quality Review. Purely
 * sequential, ambient-only `.text()` calls (no explicit x/y, no tables)
 * — matching `SignalReportPdfService`'s own established "never bitten
 * by the pdfkit cursor-leak bug class because nothing pins an explicit
 * position for a later call to inherit" discipline. Verified via a real
 * render + `pdftotext -layout` readback before being considered done,
 * per CLAUDE.md's own three-times-recurring gotcha.
 */
@Injectable()
export class PqrPdfService {
  async render(data: PqrData): Promise<Buffer> {
    const doc = new PDFDocument({ size: 'A4', margin: PAGE_MARGIN })
    const chunks: Buffer[] = []

    const result = new Promise<Buffer>((resolve, reject) => {
      doc.on('data', (chunk: Buffer) => chunks.push(chunk))
      doc.on('end', () => resolve(Buffer.concat(chunks)))
      doc.on('error', reject)
    })

    const section = (heading: string) => {
      doc.moveDown(0.8)
      doc.font('Helvetica-Bold').fontSize(11).fillColor('#000000').text(heading)
      doc.font('Helvetica').fontSize(10)
      doc.moveDown(0.3)
    }
    const field = (label: string, value: string | number | null | undefined) => {
      doc.font('Helvetica-Bold').text(`${label}: `, { continued: true })
      doc.font('Helvetica').text(value === null || value === undefined ? 'Not recorded' : String(value))
    }

    doc.font('Helvetica-Bold').fontSize(14).text('PRODUCT QUALITY REVIEW (PQR)')
    doc.font('Helvetica').fontSize(9).fillColor('#6B7280')
    doc.text(`${data.companyName} — ${data.productName}`)
    doc.text(`Review period: ${formatDate(data.periodStart)} to ${formatDate(data.periodEnd)}`)
    doc.text(`Generated ${formatDate(data.generatedAt)}`)
    doc.fillColor('#000000').fontSize(10)

    section('1. Batches Manufactured')
    field('Batches in period', data.batchCount)

    section('2. Deviations & CAPAs')
    field('Deviations opened in period', data.deviationCount)
    field('CAPAs opened in period', data.capaCount)

    section('3. Out-of-Specification / Out-of-Trend Results')
    field('OOS/OOT investigations in period', data.oosCount)

    section('4. Complaints')
    field('Complaints received in period', data.complaintCount)

    section('5. Change Controls')
    field('Changes assessed in period', data.changeControlCount)

    section('6. Stability')
    field('Stability data', data.stabilityNote)

    section('7. Regulatory Activity')
    field('Submissions in period', data.regSubmissionCount)
    field('Variations in period', data.regVariationCount)

    section('8. Open Quality Trend Flags')
    if (data.openQualityTrendFlags.length === 0) {
      doc.text('None open.')
    } else {
      for (const flag of data.openQualityTrendFlags) {
        doc.text(`•  ${flag}`, { indent: 12 })
      }
    }

    section('9. Conclusions & Trends')
    field('Conclusions', data.conclusionsNarrative)
    field('Trends', data.trendsNarrative)

    section('10. Recommended Actions')
    if (data.recommendedActions.length === 0) {
      doc.text('None recorded.')
    } else {
      for (const action of data.recommendedActions) {
        doc.text(
          `•  ${action.description}${action.capaOpened ? ' (CAPA opened)' : ''}`,
          { indent: 12 },
        )
      }
    }

    section('11. Review & Sign-Off')
    field('Reviewed by', data.reviewedByFullName)
    field('Reviewed at', data.reviewedAt ? formatDate(data.reviewedAt) : null)

    doc.moveDown(1.5)
    doc.fontSize(8.5).fillColor('#6B7280').text(
      'This Product Quality Review is generated by SafeMeds from the product\'s own quality records as they stood at assembly time, per ICH Q10\'s continual-improvement framework. Data pulled live at assembly is frozen into this document and is not re-queried after generation.',
      { align: 'justify' },
    )

    doc.end()
    return result
  }
}
